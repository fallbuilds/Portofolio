export function setLanguage(lang) {
    if (!translations[lang]) lang = 'id';
    localStorage.setItem('user_lang', lang);

    const dict = translations[lang];

    // Update text elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            el.textContent = dict[key];
        }
    });

    // Update placeholders with data-i18n-ph
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
        const key = el.getAttribute('data-i18n-ph');
        if (dict[key] !== undefined) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    // Update typewriter data-text for hero if present
    const twP = document.getElementById('tw-p');
    if (twP && dict['hero.desc']) {
        twP.setAttribute('data-text', dict['hero.desc']);
        twP.textContent = dict['hero.desc'];
    }

    // Update language switch button styles
    const btnId = document.getElementById('btn-lang-id');
    const btnEn = document.getElementById('btn-lang-en');

    if (btnId && btnEn) {
        if (lang === 'id') {
            btnId.className = 'px-2 py-0.5 rounded transition-all duration-200 text-accent-cyan font-bold bg-accent-cyan/20';
            btnEn.className = 'px-2 py-0.5 rounded transition-all duration-200 text-gray-400 hover:text-gray-200';
        } else {
            btnEn.className = 'px-2 py-0.5 rounded transition-all duration-200 text-accent-cyan font-bold bg-accent-cyan/20';
            btnId.className = 'px-2 py-0.5 rounded transition-all duration-200 text-gray-400 hover:text-gray-200';
        }
    }

    document.documentElement.setAttribute('lang', lang);
}

export function initI18n() {
    const savedLang = localStorage.getItem('user_lang') || 'id';

    const btnId = document.getElementById('btn-lang-id');
    const btnEn = document.getElementById('btn-lang-en');

    if (btnId) {
        btnId.addEventListener('click', () => setLanguage('id'));
    }
    if (btnEn) {
        btnEn.addEventListener('click', () => setLanguage('en'));
    }

    // Apply initial language
    setLanguage(savedLang);
}
